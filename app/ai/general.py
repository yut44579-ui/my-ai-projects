# ════════════════════════════════════════════════════════════════════════
# ①″ 概念问法的判据（★ FR-012 组 3：**全项目唯一一处**）
#
# 为什么收在这一处：判据原来分居两地 —— 路由那一侧（`routing._GENERAL_TERM_RE`）只认
# **前缀式**（「什么是 X」），这里那一份只负责抠词。于是「毛利率是什么意思」这种
# **后缀式**说法两边都认不出来，一路掉进澄清档，而且**先读了一遍销售数据**
# （用户问一个词的意思，系统去查了 11 月的流水）。两处词表早晚会漂移成
# "判得出来却答不上来"，所以合并到这里，路由只 import 来用。
# ════════════════════════════════════════════════════════════════════════
#: 概念/定义的问法（前缀式与后缀式各一组，抠词与判路共用）
CONCEPT_PATTERNS: tuple[str, ...] = (
    "什么是", "是什么意思", "是啥意思", "指的是什么", "指什么", "怎么理解", "如何理解",
    "解释一下", "解释下", "的定义", "什么概念", "有什么用", "干什么用的", "为什么叫",
    "是什么", "是啥",
)

#: 概念问句里**不该出现**的东西：一出现就说明用户在问数据，不是问概念。
#: （★ 这一张表**逐字继承** FR-007 的 `routing._GENERAL_BLOCKERS` —— 放宽它就会把
#:   「2011年11月的毛利是多少」「销售趋势是什么意思」这类**问数据**的句子抢成概念说明。）
CONCEPT_BLOCKERS: tuple[str, ...] = (
    "最", "排行", "排名", "哪些", "哪个", "多少", "几", "趋势", "对比", "比较", "占比",
    "月", "年", "周", "今天", "昨天", "最近", "本期", "上期", "报表", "数据", "导出", "下载",
)

_CONCEPT_TERM = r"(.{1,16}?)"
#: 前缀式：「什么是毛利率」→ 词在模式**后面**
_CONCEPT_PREFIX_RE = re.compile(
    r"(?:什么是|指的是什么|怎么理解|如何理解|解释一下|解释下)" + _CONCEPT_TERM + r"[？?。！!,，；;]?$"
)
#: 后缀式：「毛利率是什么意思」→ 词在模式**前面**（FR-012 组 3 补的就是这一种自然说法）。
#: 「是什么 / 是啥」放在最后：它们在中文里既可能是问概念，也可能是问某个数的取数方式 ——
#: 所以这条**仍然要过 `CONCEPT_BLOCKERS`**（「这个数据的口径是什么」会被"数据"挡回去）。
_CONCEPT_SUFFIX_RE = re.compile(
    _CONCEPT_TERM + r"(?:是什么意思|是啥意思|是什么|是啥)[？?。！!,，；;]?$"
)

# 词尾要剥掉的东西：句读 + 引号书名号 + 语气词（"什么是毛利率？"→"毛利率"）
_TERM_TRIM = "？?。！!,，；;：:「」\"'“”《》【】 \t的"


def extract_term(question: str) -> str:
    """把概念问句里的**那个词**抠出来（"什么是毛利率？"/"毛利率是什么意思"→"毛利率"）。

    两种语序都认（前缀式 / 后缀式），用的就是上面那两个**判路同一个**正则 ——
    判得出来才抠得出词，抠不出词就说明这句话不是概念问句（不猜）。
    """
    text = (question or "").strip()
    for pattern in (_CONCEPT_SUFFIX_RE, _CONCEPT_PREFIX_RE):
        match = pattern.search(text)
        if match:
            term = match.group(1).strip().strip(_TERM_TRIM)
            if term:
                return term
    return ""


def is_concept_question(question: str) -> bool:
    """这句话是在问**一个词的意思**吗（纯代码，不读数据、不调模型）—— 路由与回答共用这一处判据。

    两件事同时成立才算：抠得出那个词 + 句子里没有"最/多少/11月/数据"这类**问数据**的信号。
    """
    text = (question or "").strip()
    if not text:
        return False
    if any(blocker in text for blocker in CONCEPT_BLOCKERS):
        return False
    return bool(extract_term(text))


def _glossary_lookup(term: str) -> str | None:
    if not term:
        return None
    lowered = term.lower()
    for keys, definition in _GLOSSARY:
        for key in keys:
            if key.isascii():
                if key in lowered:
                    return definition
            elif key in term:
                return definition
    return None


def general_answer(question: str, *, use_llm: bool = True) -> tuple[str, str, str]:
    """概念问答/闲聊 → (标题, 正文, 来源)。

    来源取值与 API 契约一致：`system`（本机词条/模板）或 `llm`（模型现写的解释）。
    **任何一条路径都不带销售数据**：喂给模型的只有用户那句问题本身。
    """
    text = (question or "").strip()
    if _is_chitchat(text):
        title, lines = _CHITCHAT_REPLY
        return title, "\n".join(lines), "system"

    term = extract_term(text)
    known = _glossary_lookup(term)
    if known:
        # 内置词条**优先于模型**：概念解释是稳定知识，本机就有准确答案时没必要外发问题
        return f"什么是{term}", known, "system"

    if use_llm and llm.available():
        try:
            body = llm.chat(_GENERAL_SYSTEM_PROMPT, text, max_tokens=llm.DEFAULT_MAX_TOKENS)
            body = (body or "").strip()
            if body:
                return (f"什么是{term}" if term else "回答"), body, "llm"
        except llm.LLMError:
            pass                                     # 掉到下面：没有可用的解释就说没有
    title = f"什么是{term}" if term else "回答"
    return title, _GLOSSARY_MISS.format(term=term or text), "system"


def _is_chitchat(text: str) -> bool:
    return bool(re.match(
        r"^(你好|您好|哈喽|嗨|在吗|在不在|hi|hello|hey|早上好|中午好|下午好|晚上好|谢谢|多谢|好的|收到|ok)"
        r"[!！。.？?~～\s]*$",
        text,
        re.IGNORECASE,
    ))


