"""分级处理：简单 / 中级 / 高级，三档的处理方式**完全不同**。

★★ 为什么要有这个东西（用户的原始需求）：

    「分一下阶级关系，简单、中级（低风险）、高级（高风险）等问题的处理方式不一样：
      简单的问题 AI 不管里面知识库有没有存，都可以回答；
      中级的问题会先正常 AI 分析，并反复确认之后再转人工 ——
      也就是用户重复提及一些模糊不清、但还是有点重要的；
      高风险，用户直接提及高风险的问题，直接转。」

★★ 这个设计的价值在于：**"转人工"不该是一个动作，而应该是三档不同的策略。**

    只做两档（能答 / 转人工）的系统，实际用起来是这样：
      · 该答的答不了 → 用户觉得笨
      · 不该答的乱答 → 客户觉得危险
    而且**人的注意力是稀缺的**：把所有拿不准的都丢给人工，
    人工队列会被淹掉，真正紧急的那条反而没人看。

    三档的意义就是**把人的注意力留给真正需要的那些**。

具体三档：

    简单（simple）
      · 寒暄、自我介绍、"你是做什么的"、道谢
      · ★ 知识库有没有都能答 —— **不检索，直接让模型答**
      · ★ 但有硬边界：只允许答"元问题"（你是谁、你能做什么），
        不许答具体业务事实。否则就成了"让模型编"，
        而这是整个项目的第一条纪律：事实由程序算，不由模型编。

    中级（medium，低风险）
      · 检索命中了但不够确定（质量在中间区间）
      · ★ 先正常答一次，**不急着转人工**
      · ★ 只有当这个用户**重复提及**（换个说法又问一遍）才转人工
      · 理由：第一次问可能是表达不清，答了之后他自己就明白了；
        但他要是换个说法又问一遍，说明**第一次的回答没解决问题** ——
        这时候再转，才不会浪费人工，也不会让用户觉得"你根本没懂我"

    高级（high，高风险）
      · 报价、折扣、合同、退款、发票、投诉、法律、赔偿、个人信息
      · ★ **直接转人工，一个字都不答**（连检索都不做）
      · 理由：这些答错一次就是真金白银的损失或法律风险，
        "先答一下看看"这个念头本身就是错的
"""

