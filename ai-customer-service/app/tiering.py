# 中级：靠"用户有没有重复提及"来决定转不转人工
# ══════════════════════════════════════════════════════════════════════

# 判定"重复提及"的相似度阈值。
REPEAT_THRESHOLD = 0.45

# ★ 这些是**语气词和套话**，不承载"在问什么"的信息。
#   算相似度之前先去掉，否则「我是说保修期」和「你们那个保修多久啊」
#   会被"我是说""那个""啊"这些词拉低相似度，判不出重复（实测踩到）。
FILLER = [
    "我是说", "就是说", "我意思是", "也就是说", "刚才说", "上面说",
    "你们", "我们", "咱", "那个", "这个", "一下", "一个",
    "请问", "麻烦", "帮我", "给我", "能不能", "可不可以", "可以",
    "怎么", "怎样", "如何", "什么", "啥", "多少", "吗", "呢", "啊", "呀", "吧", "的", "了",
]


def _grams(s: str) -> set[str]:
    """中文 2-gram 集合（和检索层同一套思路，保证口径一致）。"""
    s = re.sub(r"[\s，。？！、,.?!；;：:\"'（）()【】\[\]《》<>~-]+", "", (s or "").lower())
    if len(s) < 2:
        return {s} if s else set()
    return {s[i : i + 2] for i in range(len(s) - 1)}


def _content_grams(s: str) -> set[str]:
    """去掉套话之后的内容 2-gram。"""
    t = (s or "").strip()
    for f in FILLER:
        t = t.replace(f, "")
    return _grams(t)


def similarity(a: str, b: str) -> float:
    """★ 用**重叠系数**（交集 / 较短那边的长度），不是杰卡德。

    为什么不用杰卡德：它会被长度差异严重惩罚。
      「保修多久」(3 个 2-gram) vs 「你们那个保修多久啊」(9 个)
      杰卡德 = 3/9 = 0.33 → 判不出重复
      重叠系数 = 3/3 = 1.0 → 判出来了
    ★ 而"用户重复提及"的场景本来就是**一次说得短、一次说得多**，
      所以必须用对长度不敏感的口径。
    """
    ga, gb = _content_grams(a), _content_grams(b)
    if not ga or not gb:
        return 0.0
    return len(ga & gb) / min(len(ga), len(gb))


def repeated_topic(question: str, history: list[str], threshold: float = REPEAT_THRESHOLD) -> dict[str, Any]:
    """这个用户是不是**在重复问同一件事**。

    ★ 这是"中级问题先答、重复才转人工"的关键判断。

    为什么要看"重复"而不是一上来就转：
      第一次问，很可能是**表达不清**，答了他自己就明白了。
      但他换个说法又问一遍 → 说明**第一次的回答没解决问题**，
      这时候再转人工，人工的注意力才没被浪费。
    """
    best = 0.0
    best_q = ""
    for h in history or []:
        s = similarity(question, h)
        if s > best:
            best, best_q = s, h
    return {
        "repeated": best >= threshold,
        "score": round(best, 3),
        "matched": best_q,
    }


# ══════════════════════════════════════════════════════════════════════
# 主判断
# ══════════════════════════════════════════════════════════════════════

def classify(
    question: str,
    *,
    quality: float | None = 0.0,
    history: list[str] | None = None,
    clarify_count: int = 0,
    auto_threshold: float = 0.72,
    draft_threshold: float = 0.45,
) -> dict[str, Any]:
    """给出这一问属于哪一档，以及**该怎么处理**。

    返回：
      tier    simple / medium / high / nonsense
      action  answer_direct / answer_then_watch / clarify / escalate_now / normal
      reason  给运维看的判断依据（会显示在控制台上）

    ★★ 判断顺序（**不能反**）：
        ① 无意义输入      → 反问澄清（不是转人工！）
        ② 硬风险          → 直接转人工
        ③ 简单问题        → 不检索，模型直接答
        ④ 软风险          → 答流程 + 把信息问全（不转人工）
        ⑤ 按检索质量分档
    """
    q = question or ""

    # ── ① 无意义输入 → 反问澄清 ────────────────────────────────────
    # ★★ 用户的批评：「不是我随便发一句话就直接接入人工，
    #    这样不是会加重客服或者销售的压力？」
    #    所以这里**绝不转人工**，先让 AI 问一句。
    if is_nonsense(q):
        if clarify_count < CLARIFY_MAX:
            return {
                "tier": "nonsense", "action": "clarify",
                "clarify_count": clarify_count + 1,
                "reason": f"看不出想干什么（第 {clarify_count + 1} 次）—— "
                          f"AI 反问澄清，**不占用人工**；"
                          f"问满 {CLARIFY_MAX} 次还说不清才转人工",
            }
        return {
            "tier": "nonsense", "action": "escalate_now",
            "reason": f"已经问过 {CLARIFY_MAX} 次还是说不清 —— 这时候才转人工",
        }

    # ── ② 软风险 → 答流程 + 问全信息，**不转人工** ─────────────────
    #
    # ★★ 必须排在硬风险**前面**！
    #   第一版把硬风险放前面，结果：
    #     「怎么报价」→ 硬规则的 `报价` 命中 → 直接转人工（错，这是在问流程）
    #     「怎么退货」→ 硬规则的 `退货` 命中 → 直接转人工（错）
    #   ★ 教训：**具体规则要排在宽泛规则前面**。
    #     "怎么报价"是"报价"的子集，先匹配宽的那个就被它吃掉了。
    sr = soft_risk_reason(q)
    if sr:
        return {
            "tier": "high", "action": "answer_process", "risk": sr, "risk_level": "soft",
            "reason": f"命中软风险「{sr}」（问流程 / 问要什么资料）—— "
                      f"AI 先答流程并把该问的信息问全，**不转人工**；"
                      f"只有真要给具体数字/承诺时才转",
        }

    # ── ③ 硬风险 → 直接转，连检索都不做 ────────────────────────────
    hr = high_risk_reason(q)
    if hr:
        return {
            "tier": "high", "action": "escalate_now", "risk": hr, "risk_level": "hard",
            "reason": f"命中硬风险「{hr}」—— 这类问题一旦答错就是真金白银的损失或法律风险，"
                      f"直接转人工，一个字都不答",
        }

    # ── ④ 简单问题 → 不检索，模型直接答 ────────────────────────────
    sp = is_simple(q)
    if sp:
        return {
            "tier": "simple", "action": "answer_direct", "kind": sp,
            "reason": f"「{sp}」类问题 —— 不需要查资料，直接由模型介绍自己；"
                      f"但严格限制不许回答任何具体业务事实",
        }

    # ── ⑤ 还没检索（第一次调用）→ 先让它走检索 ─────────────────────
    # ★★ `quality is None` 和 `quality == 0` 是**两件完全不同的事**：
    #     None  = 还没查过资料
    #     0.0   = 查过了，什么都没找到
    #   第一版没区分，于是所有需要查资料的问题都在检索之前
    #   被判成"检索没命中 → 先澄清" ——【打样要多久】都被反问了（实测踩到）。
    if quality is None:
        return {
            "tier": "medium", "action": "normal",
            "reason": "还没检索 —— 先让检索走完再判断分档",
        }

    # ── ⑥ 按检索质量分档 ───────────────────────────────────────────
    rep = repeated_topic(q, history or [])
    if quality >= auto_threshold:
        return {
            "tier": "medium", "action": "normal", "repeat": rep,
            "reason": f"检索命中充分（{quality}）—— 正常回答"
                      + (f"；★ 但用户已经重复问过（相似度 {rep['score']}）" if rep["repeated"] else ""),
        }
    if quality >= draft_threshold:
        if rep["repeated"]:
            return {
                "tier": "medium", "action": "escalate_now", "repeat": rep,
                "reason": f"检索只能算中等（{quality}），而且**用户重复提及了**"
                          f"（和上次「{rep['matched'][:20]}」相似度 {rep['score']}）"
                          f"—— 说明第一次的回答没解决问题，转人工",
            }
        return {
            "tier": "medium", "action": "answer_then_watch", "repeat": rep,
            "reason": f"检索中等（{quality}）—— **先正常答一次**，不急着转人工；"
                      f"如果他换个说法又问一遍，就转人工（第一次可能只是表达不清）",
        }

    # 检索基本没命中 → ★ 也先澄清一次，不要一上来就转人工
    if clarify_count < 1:
        return {
            "tier": "medium", "action": "clarify", "clarify_count": clarify_count + 1,
            "repeat": rep,
            "reason": f"检索质量低（{quality}），资料里没找到 —— "
                      f"先反问澄清一次（可能是问法对不上），**再考虑转人工**",
        }
    return {
        "tier": "medium", "action": "escalate_now", "repeat": rep,
        "reason": f"检索质量过低（{quality}），资料里确实没有相关内容"
                  + ("；而且用户已重复提及" if rep["repeated"] else ""),
    }
