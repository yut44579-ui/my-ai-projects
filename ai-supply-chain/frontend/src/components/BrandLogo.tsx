import { useId } from 'react'

/**
 * 小笋供应链 · 品牌图标
 *
 * ═══════════════════════════════════════════════════════════════
 * 【只取参考图的"元素"，不复制那张图】
 * ═══════════════════════════════════════════════════════════════
 *   参考图（微信小程序码里的卡通笋）里可借用的元素有三个：
 *     ① **黄绿色的竹子色**（不是普通的深绿）—— 这个色最容易被认成"笋"
 *     ② **层叠的叶片**：笋是一层叶子包一层叶子长大的，边缘是弧线不是直线
 *     ③ **圆润友好的形**：不尖锐、不硬朗
 *
 *   本图标吸取的是这三样，但**没有**画眼睛/手脚/笑脸那些角色化特征 ——
 *   那些属于参考图那个卡通形象，直接搬过来会让产品看起来像儿童应用，
 *   与 §七「清晰、克制、企业级」的要求冲突。
 *
 * ═══════════════════════════════════════════════════════════════
 * 【图标要传达的意思】
 * ═══════════════════════════════════════════════════════════════
 *   小笋     → 白色笋形，带**侧叶**与**顶芽**（参考图里的叶片元素）
 *   AI供应链 → 笋壳的层叠分节线，两端各一个**连接节点**。
 *              笋一节一节长、供应链一环一环接 —— 同一组"分节"表达两个意思。
 *   AI       → 左上角四角星芒
 *
 * ═══════════════════════════════════════════════════════════════
 * 【配色】
 * ═══════════════════════════════════════════════════════════════
 *   底板渐变：黄绿 #A3D65C（笋/供应）→ 蓝 #0E7FC4（科技/AI），对角过渡
 *   之所以用**黄绿而不是深绿**：深绿偏"金融/环保"，黄绿才是竹笋本来的颜色。
 *
 * ═══════════════════════════════════════════════════════════════
 * 【为什么内联 SVG 而不是图片】
 * ═══════════════════════════════════════════════════════════════
 *   侧栏深色底、登录页浅色底，矢量图任意尺寸都清晰；跟随 size 参数缩放；
 *   无额外网络请求，首屏不闪。
 *   ★ favicon 无法复用本组件（HTML 与 TSX 是两套运行环境），
 *     所以 `public/favicon.svg` 是**同一份图形的另一份拷贝**。
 *     改图形时两处都要改 —— 已记进 docs/DECISIONS.md D50。
 */

type BrandLogoProps = {
  /** 边长（px）。侧栏用 36，登录页可用 64 */
  size?: number
  /** 是否带圆角底板。favicon / 应用图标要底板；放在已有底色的容器里可关掉 */
  withPlate?: boolean
  style?: React.CSSProperties
}

/**
 * 品牌图形主体，viewBox 固定 0 0 48 48。
 *
 * ★ `gradientId` 由调用方传入**每个实例唯一**的值（useId）：
 *   同一 id 在页面里出现两次是无效 HTML，且后出现的实例会"借用"第一个的定义。
 *   现在两份定义相同看不出问题，但只要将来改动其中一处（例如深色底换配色）
 *   就会变成很难查的 bug。
 */
function BrandMark({ gradientId }: { gradientId: string }) {
  return (
    <>
      <defs>
        {/* ★ gradientUnits="userSpaceOnUse" 很关键：
            默认的 objectBoundingBox 会按**每个元素的包围盒**重新映射渐变，
            于是三层叶鞘各自取到的颜色不一致，叠在一起会看出色差。
            绑定到 48×48 画布后，三层在同一位置取到同一颜色，叠加才自然。 */}
        <linearGradient
          id={gradientId}
          x1="0"
          y1="0"
          x2="48"
          y2="48"
          gradientUnits="userSpaceOnUse"
        >
          <stop offset="0" stopColor="#A3D65C" />
          <stop offset="1" stopColor="#0E7FC4" />
        </linearGradient>
      </defs>

      {/*
        三层叶鞘叠成笋形。
        ★ 为什么不画"笋身 + 两道横线"（我第一版的做法）：
          横线在缩小后读起来像**螺纹/螺旋**，不像笋。
          真正的笋是**一片叶鞘包一片叶鞘**长起来的 —— 所以用三层
          带尖角的鞘片叠压，层与层之间靠**不透明度差**分开（1 / .88 / .76），
          而不是靠描边。这样即使 16px 也能看出"层"，且没有硬线条糊在一起。
      */}
      {/* 外层：最宽，底边圆润 */}
      <path
        d="M11.7 29.6 C11.7 36.1 17.1 40.2 24 40.2 C30.9 40.2 36.3 36.1 36.3 29.6 C32.9 32.4 27.6 33.5 24 33.5 C20.4 33.5 15.1 32.4 11.7 29.6 Z"
        fill="#FFFFFF"
      />
      {/* 中层 */}
      <path
        d="M14.2 22.4 C14.2 29.9 18.7 33.5 24 33.5 C29.3 33.5 33.8 29.9 33.8 22.4 C30.7 25.9 27 27.1 24 27.1 C21 27.1 17.3 25.9 14.2 22.4 Z"
        fill="#FFFFFF"
        opacity="0.88"
      />
      {/* 内层（笋尖）：向上收成尖角 */}
      <path
        d="M18.2 17.2 C18.2 25.4 21 27.4 24 27.4 C27 27.4 29.8 25.4 29.8 17.2 C29.8 12.4 27.6 8.2 24 4.9 C20.4 8.2 18.2 12.4 18.2 17.2 Z"
        fill="#FFFFFF"
        opacity="0.76"
      />

      {/*
        ★★ 供应链 / AI 语义：**三节点相连的网络**（TASK-034 第二版）
          第一版这里放的是"四角星芒"，用户反馈「方向对，但少了 AI 供应链的元素」。
          星芒只说"AI"，不说"供应链"。换成**相连的节点**后一个元素说两件事：
            · 节点相连 = 供应链的"环环相扣"
            · 网络形态   = AI / 数据
          ★ 为什么不做成更直白的图形（我试过并放弃）：
            · 节点链沿笋身向上 → 像笋长了条尾巴/根须（V2）
            · 底部横向连线     → 像一条底座，且 16px 缩成一条糊线（V3）
            · 每层两侧加节点   → 像笋身长了小耳朵（V4）
          位置也试出来的：放左上角、保持小尺寸，才不会与笋尖形成"两个主体"。
      */}
      <path
        d="M7.4 8.3 L13.3 5.7 M7.4 8.3 L11.4 13.6"
        stroke="#FFFFFF"
        strokeWidth="1.2"
        strokeLinecap="round"
        opacity="0.9"
      />
      <circle cx="7.4" cy="8.3" r="2.3" fill="#FFFFFF" />
      <circle cx="13.5" cy="5.6" r="1.65" fill="#FFFFFF" opacity="0.9" />
      <circle cx="11.5" cy="13.7" r="1.65" fill="#FFFFFF" opacity="0.9" />
    </>
  )
}

/**
 * 默认导出：带圆角底板的完整图标（侧栏、登录页、应用图标都用它）。
 */
export default function BrandLogo({ size = 36, withPlate = true, style }: BrandLogoProps) {
  const uid = useId()
  const gradientId = `xs-brand-${uid.replace(/:/g, '')}`

  return (
    <svg
      width={size}
      height={size}
      viewBox="0 0 48 48"
      fill="none"
      style={style}
      role="img"
      aria-label="小笋供应链"
    >
      {/* 圆角底板：rx 按 48 画布取 11，与侧栏原有 36px/10px 的观感一致 */}
      {withPlate && <rect width="48" height="48" rx="11" fill={`url(#${gradientId})`} />}
      <BrandMark gradientId={gradientId} />
    </svg>
  )
}
